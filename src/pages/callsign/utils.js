function parseChinaCallSign(input) {
    const normalized = input.toUpperCase().replace(/\s/g, '');

    if (normalized === 'BS7H') {
        return {
            province: '黄岩岛'
        }
    } else if (normalized === 'BV9P') {
        return {
            province: '东沙岛'
        }
    } else if (normalized === 'B100IARU') {
        return {
            type: 'CRAC庆祝IARU成立100周年纪念活动临时电台'
        }
    } else if (['BM', 'BN', 'BO', 'BP', 'BQ', 'BU', 'BV', 'BW', 'BX'].includes(normalized.slice(0, 2))) {
        // 参考 https://www.bilibili.com/opus/360131152346442255
        const regionMap = {
            '0': '临时电台',
            '1': '基隆、宜兰',
            '2': '台北',
            '3': '桃园、新竹',
            '4': '苗栗、台中',
            '5': '彰化、南投、云林',
            '6': '嘉义、台南',
            '7': '高雄',
            '8': '屏东、台东、花莲',
            '9': '台湾省以外地区的业余电台或临时电台'
        };
        
        const regionCode = normalized.slice(2, 3);
        const region = regionMap[regionCode] || '未知地区';
        
        const suffix = normalized.slice(3);
        let type = '';
        
        if (suffix.length === 1) {
            if (normalized[1] === 'X') {
                type = '中继台';
            } else {
                type = '特殊业余电台';
            }
        } else if (suffix.length === 2) {
            type = '一级业余电台';
        } else if (suffix.length === 3) {
            if (normalized[1] === 'X') {
                type = '二级业余电台';
            } else {
                type = '三级业余电台';
            }
        }
        
        return {
            province: '台湾省',
            region,
            type
        };
    }
    
    // 处理移动操作格式（如 B0/BG1ZZZ）
    const [baseCall, regionOverride] = normalized.split('/').reverse();
    
    // 主呼号解析
    const mainMatch = baseCall.match(/^B([A-Z])(\d)([A-Z]{1,3})$/);
    if (!mainMatch) {
      // 如果不符合正则，尝试提取有用信息
      const typeMatch = baseCall.match(/^B([A-Z])/);
      const regionMatch = baseCall.match(/^B[A-Z](\d)/);
      
      return { 
        type: typeMatch ? radioConfig.stationTypes[typeMatch[1]] || '' : '',
        province: regionMatch ? radioConfig.regions[regionMatch[1]].join('/') || '' : '',
        original: baseCall
      };
    }

    console.log(mainMatch)
  
    const [_, typeCode, regionCode, suffix] = mainMatch;
    
    // 检测保留字符
    if (radioConfig.stationTypes._reserved.includes(typeCode)) {
      return { error: "保留序列不可用" };
    }
  
    // 获取候选省份
    const candidates = radioConfig.regions[regionCode] || [];
    const suffixKey = suffix.substring(0,1); // 取前两位关键字符

    console.log(candidates, suffixKey)
    
    // 省份匹配（包含海南特殊处理）
    const province = candidates.find(prov => {
      const { start, end } = radioConfig.suffixRules[prov];
      console.log('start, end', start, end)
      return isInRange(suffixKey, start, end) || 
        (prov === '海南' && suffix.startsWith('Y'));
    });

    console.log('province', province)
  
    // 构建结果
    const result = {
      type: radioConfig.stationTypes[typeCode] || '未知类型',
      province: province || '未知地区',
      regionCode
    };
  
    // 处理移动操作标识
    if (regionOverride) {
      result.isMobile = true;
      result.operationRegion = `B${regionCode}`;
      result.notes = "符合异地操作规范[1,2](@ref)";
    }
  
    return result;
}

  // 辅助函数：检测字符范围
function isInRange(suffix, start, end) {
    console.log('suffix, start, end', suffix, start, end)
    const code = suffix.charCodeAt(0) * 1000;
    const min = start.charCodeAt(0) * 1000;
    const max = end.charCodeAt(0) * 1000;
    return code >= min && code <= max;
}

